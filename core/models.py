import uuid

from django.contrib.auth.models import AbstractUser
from django.db import models


class User(AbstractUser):
    """
    Application user.

    is_admin controls access to:
    - all results,
    - XLSX export,
    - user management.
    """

    is_admin = models.BooleanField(default=False)

    def __str__(self):
        return self.username


YES_NO_CHOICES = [
    ("Sí", "Sí"),
    ("No", "No"),
]

MODE_CHOICES = [
    ("self", "Autoadministrado"),
    ("administered", "Administrado a sujeto"),
]


class TestSession(models.Model):
    """
    One application of the FAPPREN VA questionnaire.

    It can be:
    - self-administered by a logged-in student,
    - administered by a logged-in student to another subject,
    - answered by a non-registered subject through a single-use link
      generated by a registered user.
    """

    created_by = models.ForeignKey(
        "core.User",
        on_delete=models.PROTECT,
        related_name="test_sessions",
    )

    mode = models.CharField(
        max_length=20,
        choices=MODE_CHOICES,
        default="self",
    )

    # Sociodemographic data
    participant_code = models.CharField(max_length=100)
    age = models.PositiveIntegerField()
    sex = models.CharField(max_length=50)
    education = models.CharField(max_length=100)
    marital_status = models.CharField(max_length=100)
    occupational_status = models.CharField(max_length=100)
    occupation_detail = models.CharField(max_length=255, blank=True)
    nationality = models.CharField(max_length=100)

    # Application data
    time_minutes = models.PositiveIntegerField(null=True, blank=True)
    had_difficulty = models.CharField(
        max_length=10,
        choices=YES_NO_CHOICES,
        blank=True,
    )
    difficulty_detail = models.TextField(blank=True)

    # Modality data
    modality = models.CharField(max_length=100, blank=True)
    evaluator_code = models.CharField(max_length=100, blank=True)
    evaluator_read_aloud = models.CharField(
        max_length=10,
        choices=YES_NO_CHOICES,
        blank=True,
    )
    received_help = models.CharField(
        max_length=10,
        choices=YES_NO_CHOICES,
        blank=True,
    )
    device = models.CharField(max_length=100, blank=True)

    created_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        return f"{self.participant_code} ({self.created_at:%Y-%m-%d %H:%M})"

    def answers_dict(self):
        """
        Returns:
            {item_number: raw_value}
        Missing items are absent from the dictionary.
        """
        return {answer.item_number: answer.value for answer in self.answers.all()}


class TestInvitation(models.Model):
    """
    Single-use link that allows a non-registered participant to answer the test.

    The resulting TestSession is linked to the user who generated the link.
    """

    token = models.UUIDField(default=uuid.uuid4, unique=True, editable=False)
    created_by = models.ForeignKey(
        "core.User",
        on_delete=models.CASCADE,
        related_name="test_invitations",
    )
    created_at = models.DateTimeField(auto_now_add=True)
    used_at = models.DateTimeField(null=True, blank=True)
    session = models.OneToOneField(
        TestSession,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="invitation",
    )

    class Meta:
        ordering = ["-created_at"]

    def __str__(self):
        status = "utilizado" if self.used_at else "pendiente"
        return f"Enlace {self.token} ({status})"

    @property
    def is_used(self):
        return self.used_at is not None


class Answer(models.Model):
    """
    Raw answer to one item.

    Items 1-39: 0 to 3.
    Item 40: number of selected aspects (0 to 9); scoring caps it at 3.
    """

    session = models.ForeignKey(
        TestSession,
        on_delete=models.CASCADE,
        related_name="answers",
    )
    item_number = models.PositiveIntegerField()
    value = models.PositiveIntegerField()
    # Only used by item 40, which allows multiple selected aspects.
    selected_options = models.JSONField(default=list, blank=True)
    # Only used by item 40 when the "Otros" option is selected.
    other_detail = models.CharField(max_length=255, blank=True)

    class Meta:
        unique_together = ("session", "item_number")
        ordering = ["item_number"]

    def __str__(self):
        return f"Item {self.item_number}: {self.value}"